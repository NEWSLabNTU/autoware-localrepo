#!/usr/bin/env python3
"""Derive a GPU-free build directory from its CUDA sibling.

    scripts/derive-cpu.py <version>/<arch>            write <version>/<arch>-cpu
    scripts/derive-cpu.py --check <version>/<arch>    fail if <version>/<arch>-cpu has drifted
    scripts/derive-cpu.py --check-all                 --check every <version>/<arch>-cpu

<arch> is amd64 or arm64. The CPU directory is never edited by hand: fixes land
in the CUDA directory and reach the CPU one by running this again. It copies
every tracked file of the CUDA directory except the source submodule, then:

  Dockerfile         FROM autoware-base:<tag> instead of :cuda-<tag>; drops the
                     CUDA environment, NVCC_APPEND_FLAGS and the cuDNN /
                     TensorRT / CUDA dev-library install
  config.yaml        builder image autoware-<ver>-<arch>-cpu-builder
  justfile           title, arch_label, and `test` also runs the smoke test
  localrepo          revision ubuntu2204 -> ubuntu2204cpu (amd64),
                     ubuntu2204sbsa -> ubuntu2204arm64cpu (arm64)
  debian-overrides   `make install` falls back to `cmake --install` when the
                     package has no install target (colcon2deb >= 0.4.2 does
                     this for generated rules; overrides are frozen copies)
  test/              plain ubuntu:22.04, ROS-only prerequisites, asserts that
                     no NVIDIA library is installed; adds a headless
                     planning-simulator smoke test

Autoware's CUDA packages check for CUDA themselves and build their CPU half or
nothing, so no package source is patched. The source submodule is added at the
CUDA directory's commit when it is missing.
"""

from __future__ import annotations

import argparse
import filecmp
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = ROOT / "scripts" / "cpu-variant"
ARCHES = {
    # arch: (CUDA revision suffix, CPU revision suffix, title)
    "amd64": ("ubuntu2204", "ubuntu2204cpu", "AMD64 GPU-free (CPU-only)"),
    "arm64": ("ubuntu2204sbsa", "ubuntu2204arm64cpu", "arm64 GPU-free (CPU-only)"),
}


def die(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


def tracked_files(sibling: str) -> list[str]:
    """Paths relative to the sibling dir, without the source submodule."""
    out = subprocess.run(
        ["git", "ls-files", "-z", "--", sibling], cwd=ROOT, check=True, capture_output=True
    ).stdout.decode()
    rels = []
    for p in filter(None, out.split("\0")):
        rel = p[len(sibling) + 1 :]
        if rel == "source" or rel.startswith("source/"):
            continue
        rels.append(rel)
    return rels


# ---------------------------------------------------------------- transforms


def dockerfile(text: str) -> str:
    """Split into instructions (with their leading comment block) and drop the CUDA ones."""
    blocks: list[list[str]] = []
    cur: list[str] = []
    cont = False
    for line in text.splitlines(keepends=True):
        cur.append(line)
        stripped = line.strip()
        if cont:
            cont = stripped.endswith("\\")
            if not cont:
                blocks.append(cur)
                cur = []
            continue
        if stripped.startswith("#") or stripped == "":
            continue
        cont = stripped.endswith("\\")
        if not cont:
            blocks.append(cur)
            cur = []
    if cur:
        blocks.append(cur)

    def instruction(block: list[str]) -> str:
        return "".join(l for l in block if not l.lstrip().startswith("#"))

    kept = []
    froms = 0
    for block in blocks:
        ins = instruction(block)
        if re.match(r"\s*ENV\s+(CUDA_HOME|CMAKE_CUDA_COMPILER|NVCC_APPEND_FLAGS)=", ins):
            continue
        if re.match(r"\s*ENV\s+(PATH|LD_LIBRARY_PATH)=/usr/local/cuda", ins):
            continue
        if re.match(r"\s*RUN\b", ins) and re.search(r"\blib(nvinfer|cudnn)", ins):
            continue
        m = re.match(r"\s*FROM (ghcr\.io/autowarefoundation/autoware-base):cuda-(\S+)\s*$", ins)
        if m:
            # Its comment block describes the CUDA image; replace it.
            block = [
                "# GENERATED by scripts/derive-cpu.py from the CUDA sibling; do not edit.\n",
                "# GPU-free build: upstream's non-CUDA base image. Autoware's CUDA and\n",
                "# TensorRT packages check CUDA_FOUND / TRT_AVAIL and build their CPU half\n",
                "# or nothing. No CUDA environment, NVCC flags, cuDNN or TensorRT here.\n",
                f"FROM {m.group(1)}:{m.group(2)}\n",
            ]
            froms += 1
        kept.append(block)
    if froms != 1:
        die("Dockerfile: expected one FROM autoware-base:cuda-<tag> line")
    out = "".join("".join(b) for b in kept)
    leftover = re.findall(r"^(?!\s*#).*(nvinfer|libcudnn|NVCC_APPEND|/usr/local/cuda).*$", out, re.M)
    if leftover:
        die(f"Dockerfile: CUDA left after transform: {leftover}")
    return out


def config_yaml(text: str, ver: str, arch: str) -> str:
    out, n = re.subn(
        rf"image_name: autoware-{re.escape(ver)}-{arch}-builder",
        f"image_name: autoware-{ver}-{arch}-cpu-builder",
        text,
    )
    if n != 1:
        die("config.yaml: image_name not found")
    return out


def justfile(text: str, ver: str, arch: str) -> str:
    title = ARCHES[arch][2]
    out, n = re.subn(r"^# Autoware \S+ .* Local Repository Builder$", f"# Autoware {ver} {title} Local Repository Builder\n# GENERATED by scripts/derive-cpu.py; edit the CUDA sibling instead.", text, count=1, flags=re.M)
    if n != 1:
        die("justfile: title line not found")
    out = re.sub(r'^arch_label := "[^"]*"$', f'arch_label := "{arch}-cpu"', out, flags=re.M)
    out, n = re.subn(r"^test:\n    \./test/run\.sh$", "test:\n    ./test/run.sh\n    ./test/smoke.sh", out, flags=re.M)
    if n != 1:
        die("justfile: `test:` recipe not found")
    out += "\n# Headless planning-simulator drive in the GPU-free test image (run after `just test`)\nsmoke:\n    ./test/smoke.sh\n"
    return out


def changelog(text: str, arch: str) -> str:
    cuda, cpu, _ = ARCHES[arch]
    out, n = re.subn(rf"^(autoware-localrepo-\S+ \(\S+?){cuda}\)", rf"\g<1>{cpu})", text, count=1)
    if n != 1:
        die(f"localrepo changelog: first entry does not end in {cuda}")
    return out


RULES_INSTALL = re.compile(
    r"^\tDESTDIR=(\S+) \$\(MAKE\) -C \.obj-\$\(DEB_HOST_GNU_TYPE\) install$", re.M
)


def rules(text: str) -> str:
    return RULES_INSTALL.sub(
        "\tif grep -q '^install:' .obj-$(DEB_HOST_GNU_TYPE)/Makefile; then \\\\\n"
        r"\t\tDESTDIR=\1 $(MAKE) -C .obj-$(DEB_HOST_GNU_TYPE) install; \\" "\n"
        "\telse \\\\\n"
        r"\t\techo 'no install target: packaging it empty (GPU-free build)'; \\" "\n"
        r"\t\tDESTDIR=\1 cmake --install .obj-$(DEB_HOST_GNU_TYPE); \\" "\n"
        "\tfi",
        text,
    )


def test_dockerfile(text: str) -> str:
    out, n = re.subn(
        r"# Uses NVIDIA CUDA base image.*?\nFROM nvidia/cuda:\S+\n",
        "# GPU-free build: plain Ubuntu, and setup-prerequisites.sh installs ROS only,\n"
        "# so no CUDA, cuDNN or TensorRT library exists in the image. A package still\n"
        "# linked against one fails apt's dependency resolution below.\n"
        "FROM ubuntu:22.04\n",
        text,
        count=1,
        flags=re.S,
    )
    if n != 1:
        die("test/Dockerfile: NVIDIA FROM block not found")
    out = out.replace(
        "# Installs: ROS 2 Humble, cuDNN, TensorRT, SpConv/Cumm\n"
        "# Use -y to skip interactive prompts and install everything\n",
        "# Installs: ROS 2 Humble only (--non-interactive skips every NVIDIA component)\n",
    )
    out, n = re.subn(
        r"/tmp/setup-prerequisites\.sh -y &&", "/tmp/setup-prerequisites.sh --non-interactive --ros &&", out
    )
    if n != 1:
        die("test/Dockerfile: prerequisites -y not found")
    out, n = re.subn(
        r'^RUN echo "Installation test completed successfully!"$',
        "# No NVIDIA library may have arrived as a dependency of autoware-full.\n"
        "RUN ! dpkg -l | grep -E '^ii +(libnvinfer|libcudnn|cuda-|libcublas|libcudart)' && \\\n"
        "    ! ldconfig -p | grep -E 'libcudart|libnvinfer|libcudnn'\n\n"
        'RUN echo "Installation test completed successfully!"',
        out,
        flags=re.M,
    )
    if n != 1:
        die("test/Dockerfile: final echo not found")
    return "# GENERATED by scripts/derive-cpu.py; edit the CUDA sibling instead.\n" + out


def test_run(text: str, ver: str, arch: str) -> str:
    out, n = re.subn(
        rf"autoware-localrepo-test:{re.escape(ver)}(-arm64)?\b", f"autoware-localrepo-test:{ver}-{arch}-cpu", text
    )
    if n != 1:
        die("test/run.sh: test image tag not found")
    # Some versions glob the deb by its CUDA revision suffix (1.5.0: *ubuntu2204_all.deb).
    cuda, cpu, _ = ARCHES[arch]
    out = out.replace(f"*{cuda}_all.deb", f"*{cpu}_all.deb")
    return out


# ------------------------------------------------------------------- derive


def derive(sibling: str, dst: Path) -> None:
    ver, arch = sibling.split("/")
    src = ROOT / sibling
    for rel in tracked_files(sibling):
        s, d = src / rel, dst / rel
        d.parent.mkdir(parents=True, exist_ok=True)
        text = None
        if rel == "Dockerfile":
            text = dockerfile(s.read_text())
        elif rel == "config.yaml":
            text = config_yaml(s.read_text(), ver, arch)
        elif rel == "justfile":
            text = justfile(s.read_text(), ver, arch)
        elif rel == "packages/autoware-localrepo/debian/changelog":
            text = changelog(s.read_text(), arch)
        elif rel.startswith("debian-overrides/") and rel.endswith("/debian/rules"):
            text = rules(s.read_text())
        elif rel == "test/Dockerfile":
            text = test_dockerfile(s.read_text())
        elif rel == "test/run.sh":
            text = test_run(s.read_text(), ver, arch)
        if text is None:
            shutil.copy2(s, d)
        else:
            d.write_text(text)
            shutil.copymode(s, d)
    for name in ("smoke.sh", "smoke-inner.sh"):
        t = (TEMPLATES / name).read_text()
        t = t.replace("@VERSION@", ver).replace("@TAG@", f"{ver}-{arch}-cpu")
        (dst / "test" / name).write_text(t)
        (dst / "test" / name).chmod(0o755)


def ensure_submodule(sibling: str, target: str) -> None:
    path = f"{target}/source"
    if (ROOT / path / ".git").exists():
        return
    cfg = lambda key: subprocess.run(  # noqa: E731
        ["git", "config", "-f", ".gitmodules", f"submodule.{sibling}/source.{key}"],
        cwd=ROOT, capture_output=True, text=True,
    ).stdout.strip()
    url, branch = cfg("url"), cfg("branch")
    commit = subprocess.run(
        ["git", "rev-parse", f"HEAD:{sibling}/source"], cwd=ROOT, check=True, capture_output=True, text=True
    ).stdout.strip()
    print(f"adding submodule {path} ({url} {branch} @ {commit[:9]})")
    cmd = ["git", "submodule", "add"] + (["-b", branch] if branch else []) + [url, path]
    subprocess.run(cmd, cwd=ROOT, check=True)
    subprocess.run(["git", "-C", path, "checkout", "-q", commit], cwd=ROOT, check=True)
    subprocess.run(["git", "add", path], cwd=ROOT, check=True)
    subprocess.run(["git", "submodule", "update", "--init", "--recursive", path], cwd=ROOT, check=True)


def owned_files(target: str) -> set[str]:
    """Every file derive() writes, relative to the CPU dir."""
    sibling = target.removesuffix("-cpu")
    return set(tracked_files(sibling)) | {"test/smoke.sh", "test/smoke-inner.sh"}


def check(sibling: str) -> bool:
    target = f"{sibling}-cpu"
    with tempfile.TemporaryDirectory() as tmp:
        derive(sibling, Path(tmp))
        bad = []
        for rel in sorted(owned_files(target)):
            a, b = Path(tmp) / rel, ROOT / target / rel
            if not b.exists() or not filecmp.cmp(a, b, shallow=False):
                bad.append(rel)
        cur = set(tracked_files(target)) if (ROOT / target).exists() else set()
        stale = sorted(cur - owned_files(target))
    for rel in bad:
        print(f"  {target}/{rel}: differs from what derive-cpu.py writes")
    for rel in stale:
        print(f"  {target}/{rel}: tracked but no longer in {sibling}")
    print(f"{target}: {'ok' if not (bad or stale) else 'DRIFTED, rerun scripts/derive-cpu.py ' + sibling}")
    return not (bad or stale)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sibling", nargs="?", help="<version>/<arch>, e.g. 1.9.0/amd64")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--check-all", action="store_true")
    a = ap.parse_args()

    if a.check_all:
        dirs = sorted(str(p.relative_to(ROOT)).removesuffix("-cpu") for p in ROOT.glob("*/*-cpu"))
        sys.exit(0 if all([check(d) for d in dirs]) else 1)
    if not a.sibling or not re.fullmatch(r"[0-9.]+/(amd64|arm64)", a.sibling.rstrip("/")):
        die("give <version>/<arch> with arch amd64 or arm64")
    sibling = a.sibling.rstrip("/")
    if not (ROOT / sibling).is_dir():
        die(f"{sibling} does not exist")
    if a.check:
        sys.exit(0 if check(sibling) else 1)

    target = f"{sibling}-cpu"
    # Remove what a previous run wrote, so files dropped from the sibling go too.
    if (ROOT / target).exists():
        for rel in owned_files(target) | set(tracked_files(target)):
            p = ROOT / target / rel
            if p.is_file() and not rel.startswith("source/"):
                p.unlink()
    derive(sibling, ROOT / target)
    ensure_submodule(sibling, target)
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
